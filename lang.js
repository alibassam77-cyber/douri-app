function getCurrentLang() {
    var saved = localStorage.getItem('douri_lang');
    return saved === 'en' ? 'en' : 'ar';
}

function t(key) {
    var lang = getCurrentLang();
    var dict = translations[lang] || translations.ar;
    if (dict[key] !== undefined) return dict[key];
    if (translations.ar[key] !== undefined) return translations.ar[key];
    return key;
}

function toggleLanguage() {
    var nextLang = getCurrentLang() === 'ar' ? 'en' : 'ar';
    localStorage.setItem('douri_lang', nextLang);
    applyLanguage();
    if (typeof filterDoctors === 'function') {
        filterDoctors();
    }
    if (typeof updateActiveBookingBanner === 'function') {
        updateActiveBookingBanner();
    }
    if (typeof refreshTicketCountdownDisplay === 'function') {
        refreshTicketCountdownDisplay();
    }
}

function applyLanguage() {
    var lang = getCurrentLang();
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    document.title = lang === 'ar'
        ? 'عيادة - نظام حجز وطوابير العيادات'
        : 'Clinic - Clinic Booking & Queue System';

    var textNodes = document.querySelectorAll('[data-i18n]');
    for (var i = 0; i < textNodes.length; i++) {
        var el = textNodes[i];
        var key = el.getAttribute('data-i18n');
        if (key) el.innerText = t(key);
    }

    var placeholders = document.querySelectorAll('[data-i18n-placeholder]');
    for (var j = 0; j < placeholders.length; j++) {
        var inp = placeholders[j];
        var pKey = inp.getAttribute('data-i18n-placeholder');
        if (pKey) inp.setAttribute('placeholder', t(pKey));
    }

    var langBtn = document.getElementById('langToggle');
    if (langBtn) {
        langBtn.innerText = t('lang_btn');
    }
}
